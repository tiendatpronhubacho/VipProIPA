#!/bin/bash
set -euo pipefail

IPA_PATH="${1:?Usage: fix-ipa-resources.sh path/to/app.ipa}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

/usr/bin/unzip -q "$IPA_PATH" -d "$TMP/unpacked"
APP_PATH="$(find "$TMP/unpacked/Payload" -maxdepth 1 -type d -name '*.app' -print -quit)"
if [[ -z "$APP_PATH" ]]; then
  echo "ERROR: IPA has no Payload/*.app bundle"
  exit 1
fi

# Compile the asset catalog with Apple's iOS asset compiler; do not ship the raw .xcassets folder.
xcrun actool "$ROOT/Resources/Assets.xcassets" \
  --compile "$TMP/compiled-assets" \
  --platform iphoneos \
  --minimum-deployment-target 16.0 \
  --app-icon AppIcon \
  --output-partial-info-plist "$TMP/asset-info.plist"

if [[ ! -f "$TMP/compiled-assets/Assets.car" ]]; then
  echo "ERROR: actool did not produce Assets.car"
  exit 1
fi
cp "$TMP/compiled-assets/Assets.car" "$APP_PATH/Assets.car"

# Merge icon metadata generated by actool into the app's Info.plist.
/usr/bin/python3 - "$APP_PATH/Info.plist" "$TMP/asset-info.plist" <<'PY'
import plistlib, sys, os
app_plist, generated_plist = sys.argv[1:]
with open(app_plist, 'rb') as f: app = plistlib.load(f)
with open(generated_plist, 'rb') as f: generated = plistlib.load(f)
for key in ('CFBundleIcons', 'CFBundleIcons~ipad', 'UIPrerenderedIcon'):
    if key in generated:
        app[key] = generated[key]
with open(app_plist, 'wb') as f: plistlib.dump(app, f, fmt=plistlib.FMT_XML, sort_keys=False)
PY

# Make localization bundles direct children of the app bundle if the resource copier nested them.
for langdir in "$APP_PATH"/Resources/*.lproj; do
  [[ -d "$langdir" ]] || continue
  name="$(basename "$langdir")"
  if [[ -e "$APP_PATH/$name" ]]; then
    echo "ERROR: Both root and Resources/$name exist; refusing to overwrite localization data"
    exit 1
  fi
  mv "$langdir" "$APP_PATH/$name"
done

# Remove source asset catalogs from the final app bundle; only compiled Assets.car belongs there.
rm -rf "$APP_PATH/Resources/Assets.xcassets" "$APP_PATH/Assets.xcassets"

# Verify the executable key names a real file in the app bundle.
/usr/bin/python3 - "$APP_PATH/Info.plist" "$APP_PATH" <<'PY'
import plistlib, sys, os
with open(sys.argv[1], 'rb') as f: p = plistlib.load(f)
exe = p.get('CFBundleExecutable')
if not exe or '$(' in exe or not os.path.isfile(os.path.join(sys.argv[2], exe)):
    raise SystemExit(f"ERROR: CFBundleExecutable does not resolve to a file: {exe!r}")
if p.get('CFBundleIdentifier') != 'com.tiendat.ogios':
    raise SystemExit('ERROR: Unexpected CFBundleIdentifier')
PY

# Repack as an IPA (unsigned state is preserved; signing is a separate step).
OUT="$TMP/$(basename "${IPA_PATH%.ipa}-resources-fixed.ipa")"
(cd "$TMP/unpacked" && /usr/bin/zip -qry "$OUT" Payload)
mv "$OUT" "$IPA_PATH"
/usr/bin/unzip -t "$IPA_PATH" >/dev/null
echo "Resource fix complete: $IPA_PATH"
