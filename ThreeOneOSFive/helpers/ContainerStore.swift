    static func resolveAppContainerPath(bundleID: String) -> String? {
        guard (try? PatchPathValidator.canonicalBundleIdentifier(bundleID)) == bundleID else {
            return nil
        }
        
        // 1. Thử tìm bằng MCM trước (Cách cũ)
        var lookupError: NSString?
        if let path = MCMActivateContainerPath(2, bundleID, false, &lookupError),
           isApplicationContainerPath(path) {
            return path
        }
        
        // 2. Nếu là Free Fire, quét trực tiếp thư mục (Bỏ qua MCM cho nhanh)
        let lowerID = bundleID.lowercased()
        if lowerID.contains("garena") || lowerID.contains("ffvn") {
            if let path = findPathByKeyword(keywords: ["garena", "ffvn", "freefire"]) {
                log("patch: keyword scan found game at \(path)")
                return path
            }
        }
        
        // 3. Quét thư mục metadata plist
        return resolveAppContainerPathByDirectoryScan(bundleID: bundleID)
    }
    
    // Quét thư mục tìm App chứa từ khóa (dùng cho Free Fire)
    private static func findPathByKeyword(keywords: [String]) -> String? {
        let dirs = enumerateDirectories(path: appDataRoot)
        for dir in dirs {
            let metadataPath = (dir as NSString).appendingPathComponent(".com.apple.mobile_container_manager.metadata.plist")
            if let data = try? Data(contentsOf: URL(fileURLWithPath: metadataPath)),
               let plist = try? PropertyListSerialization.propertyList(from: data, options: [], format: nil) as? [String: Any],
               let id = plist["MCMMetadataIdentifier"] as? String {
                let lower = id.lowercased()
                for kw in keywords {
                    if lower.contains(kw) {
                        let canonical = ContainerDiscoveryMerger.canonicalPath(dir)
                        if isApplicationContainerPath(canonical) { return canonical }
                    }
                }
            }
        }
        return nil
    }

    static func resolveAppContainerPathByDirectoryScan(bundleID: String) -> String? {
        let dirs = enumerateDirectories(path: appDataRoot)
        for dir in dirs {
            let metadataPath = (dir as NSString).appendingPathComponent(".com.apple.mobile_container_manager.metadata.plist")
            if let data = try? Data(contentsOf: URL(fileURLWithPath: metadataPath)),
               let plist = try? PropertyListSerialization.propertyList(from: data, options: [], format: nil) as? [String: Any],
               let id = plist["MCMMetadataIdentifier"] as? String,
               id == bundleID {
                let canonical = ContainerDiscoveryMerger.canonicalPath(dir)
                if isApplicationContainerPath(canonical) {
                    return canonical
                }
            }
        }
        return nil
    }

